    public static IEnumerable<(string Name, Action Run)> Cases =>
    [
        ("Settings tidy 1731: no setting lost: every key of 0.1730 is still on the page, in one category", () =>
        {
            Check(Before.Length == 290, "290 settings at 0.1730");
            var tabs = TenshoAssistant.SettingsIndex.Entries.Select(entry => entry.Key).ToArray();
            Check(tabs.Distinct().Count() == tabs.Length, "each setting once");
            foreach (var key in Before)
                Check(tabs.Contains(key) && TenshoAssistant.SettingsIndex.Categories.ContainsKey(key), key + ": lost");
        }),
        ("Settings tidy 1731: each moved setting beside its subject; Header and home keeps the header and the home page only", () =>
        {
            var tabs = TenshoAssistant.SettingsIndex.Entries.ToDictionary(entry => entry.Key, entry => entry.Tab);
            string Place(string key) => tabs[key] + " › " + TenshoAssistant.SettingsIndex.Categories[key];
            foreach (var (key, place) in new[]
            {
                ("Advanced.CloseOnGameWindow", "General › WindowOpening"), ("Tracker.Setting", "Tracking › Alarms"), ("Settings.MarketHover", "General › ItemTooltips"),
                ("Advanced.HoverRefresh", "General › ItemTooltips"), ("Advanced.Undercut", "General › ItemsMarket"), ("Advanced.RetainerSales", "Panels › GamePanels"),
            })
                Check(Place(key) == place, key + " is in " + Place(key));
            var header = TenshoAssistant.SettingsIndex.Categories.Where(pair => pair.Value == "Header").Select(pair => pair.Key).OrderBy(key => key, StringComparer.Ordinal).ToArray();
            Check(header.SequenceEqual(["Advanced.HeaderClock", "Advanced.HeaderEt", "Advanced.HomeTools"]), "Header and home: " + string.Join(", ", header));
            var sources = TenshoAssistant.SettingsIndex.Categories.Where(pair => pair.Value == "Sources").Select(pair => pair.Key).ToArray();
            Check(sources.All(key => key.StartsWith("Advanced.Use", StringComparison.Ordinal) || key is "Advanced.Lumina" or "Advanced.Garland" or "Advanced.Wiki" or "Advanced.GatherBuddy" or "Advanced.Teamcraft" or "Advanced.Fashion" or "Advanced.Paissa" or "Advanced.Universalis"),
                "Community sources: the sources and their uses only: " + string.Join(", ", sources));
        }),
        ("Settings tidy 1731: wiring: the moved rows drawn once, by their category; the categories named after what they hold; pictured", () =>
        {
            var advanced = Read("MainWindow.Advanced.cs"); var settings = Read("MainWindow.Settings.cs");
            foreach (var method in new[] { "DrawCloseOnGameWindowSetting", "DrawTrackerWindowSetting", "DrawMarketHoverSettings", "DrawUndercutSetting", "DrawRetainerSalesSetting" })
                Check(advanced.Contains("private void " + method + "()", StringComparison.Ordinal), method);
            Check(settings.Contains("DrawCloseOnGameWindowSetting();", StringComparison.Ordinal) && settings.Contains("DrawMarketHoverSettings();", StringComparison.Ordinal)
                && settings.Contains("DrawUndercutSetting();", StringComparison.Ordinal) && settings.Contains("DrawRetainerSalesSetting();", StringComparison.Ordinal)
                && Read("MainWindow.Alarms.cs").Contains("DrawTrackerWindowSetting();", StringComparison.Ordinal), "called by their category");
            var sources = advanced[advanced.IndexOf("private void DrawSourceSettings()", StringComparison.Ordinal)..];
            sources = sources[..sources.IndexOf("\n    }\n", StringComparison.Ordinal)];
            Check(!sources.Contains("Settings.MarketHover", StringComparison.Ordinal) && !sources.Contains("Advanced.Undercut", StringComparison.Ordinal) && sources.Contains("localization.Get(\"Advanced.MarketMoved\")", StringComparison.Ordinal), "the sources say where the prices on hover went");
            var fr = Read("Localization/Languages/fr.json"); var en = Read("Localization/Languages/en.json");
            Check(fr.Contains("\"WindowOpening\": \"Ouverture et fermeture de la fenêtre\"", StringComparison.Ordinal) && fr.Contains("\"ItemTooltips\": \"Survol et clic droit des objets\"", StringComparison.Ordinal)
                && fr.Contains("\"Alarms\": \"Alerte\"", StringComparison.Ordinal) && fr.Contains("\"Undercut\": \"Tableau des ventes : copier l'offre la plus basse moins 1\"", StringComparison.Ordinal), "fr");
            Check(en.Contains("\"WindowOpening\": \"Window opening and closing\"", StringComparison.Ordinal) && en.Contains("\"ItemTooltips\": \"Item hover and right-click\"", StringComparison.Ordinal)
                && en.Contains("\"Alarms\": \"Alarm\"", StringComparison.Ordinal) && en.Contains("\"MarketMoved\": \"Market prices on hover: Settings › General › Item hover and right-click.\"", StringComparison.Ordinal), "en");
            var plan = File.ReadAllText(Path.GetFullPath("src/TenshoAssistant.Desktop/ReferencePlan.cs"));
            foreach (var shot in new[] { "(\"Header\",\"General\",\"Header\",1280)", "(\"ItemTooltips\",\"General\",\"ItemTooltips\",1280)", "(\"ServerBar\",\"Tracking\",\"ServerBar\",1280)", "(\"Sources\",\"Data\",\"Sources\",1280)" })
                Check(plan.Contains(shot, StringComparison.Ordinal), "pictured: " + shot);
        }),
    ];
